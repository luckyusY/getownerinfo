import Link from "next/link";
import { ArrowLeft } from "lucide-react";
import PrintButton from "./PrintButton";

/**
 * The frame every generated document shares: an identifying header, the body,
 * and a footer that says what the document is and is not.
 *
 * Laid out for A4 on paper and for a phone on screen from the same markup.
 * The `print-sheet` and `print:` rules in globals.css strip the toolbar, the
 * card chrome and the page background when it goes to paper, so the printed
 * sheet carries the document and nothing else.
 */
export default function DocumentShell({
  kindLabel,
  title,
  docNumber,
  issuedOn,
  meta = [],
  backHref,
  backLabel = "Back",
  children,
  footnote,
}) {
  return (
    <div className="min-h-screen bg-panel py-6 print:bg-white print:py-0">
      <div className="mx-auto w-full max-w-3xl px-4 print:max-w-none print:px-0">
        <div className="mb-4 flex flex-wrap items-center justify-between gap-3 print:hidden">
          {backHref ? (
            <Link
              href={backHref}
              className="inline-flex min-h-11 items-center gap-2 text-sm font-bold text-ink-soft transition hover:text-ink"
            >
              <ArrowLeft className="h-4 w-4" /> {backLabel}
            </Link>
          ) : (
            <span />
          )}
          <PrintButton />
        </div>

        <article className="print-sheet rounded-2xl border border-line bg-surface p-6 shadow-soft sm:p-10 print:rounded-none print:border-0 print:p-0 print:shadow-none">
          <header className="flex flex-wrap items-start justify-between gap-4 border-b-2 border-ink/80 pb-5">
            <div>
              <p className="font-display text-xl font-black tracking-tight text-ink">getownerinfo</p>
              <p className="mt-0.5 text-xs font-semibold text-ink-faint">
                Property and asset marketplace · Rwanda
              </p>
            </div>
            <div className="text-right">
              <p className="text-[11px] font-black uppercase tracking-widest text-ink-faint">
                {kindLabel}
              </p>
              <p className="mt-0.5 font-mono text-sm font-bold text-ink">{docNumber}</p>
              <p className="mt-0.5 text-xs font-semibold text-ink-faint">Issued {issuedOn}</p>
            </div>
          </header>

          <h1 className="mt-6 font-display text-2xl font-bold leading-snug text-ink">{title}</h1>

          {meta.length > 0 && (
            <dl className="mt-5 grid gap-x-8 gap-y-3 sm:grid-cols-2">
              {meta.map(({ label, value }) => (
                <div key={label} className="border-b border-line pb-2">
                  <dt className="text-[11px] font-black uppercase tracking-wide text-ink-faint">
                    {label}
                  </dt>
                  <dd className="mt-0.5 text-sm font-bold text-ink">{value}</dd>
                </div>
              ))}
            </dl>
          )}

          <div className="mt-7">{children}</div>

          <footer className="mt-10 border-t border-line pt-4 text-[11px] font-semibold leading-5 text-ink-faint">
            {footnote}
            <p className="mt-2">
              Generated by getownerinfo on {issuedOn}. This document reflects the record held
              on the platform at the time of printing.
            </p>
          </footer>
        </article>
      </div>
    </div>
  );
}

/**
 * A money table with a highlighted total — the shape a receipt and an invoice
 * both need.
 */
export function AmountTable({ rows, total }) {
  return (
    <table className="w-full text-sm">
      <tbody>
        {rows.map(({ label, value, hint }) => (
          <tr key={label} className="border-b border-line">
            <th scope="row" className="py-2.5 text-left font-semibold text-ink-soft">
              {label}
              {hint && <span className="block text-xs font-semibold text-ink-faint">{hint}</span>}
            </th>
            <td className="py-2.5 text-right font-bold tabular-nums text-ink">{value}</td>
          </tr>
        ))}
      </tbody>
      {total && (
        <tfoot>
          <tr className="border-t-2 border-ink/80">
            <th scope="row" className="py-3 text-left font-black uppercase tracking-wide text-ink">
              {total.label}
            </th>
            <td className="py-3 text-right font-display text-lg font-black tabular-nums text-ink">
              {total.value}
            </td>
          </tr>
        </tfoot>
      )}
    </table>
  );
}
